# The files structure has maps like `static const Map<String, String> _enValues = {` ... `};`
# We want to insert our translations right before the closing `};` of each map.

import re

for lang, trans in translations.items():
    # Find the end of the map
    pattern = r'(static const Map<String, String> _' + lang + r'Values = \{.*?)(\n  \};)'
    match = re.search(pattern, text, re.DOTALL)
    if match:
        new_text = match.group(1) + "\n" + trans + match.group(2)
        text = text[:match.start()] + new_text + text[match.end():]
    else:
        print(f"Could not find _{lang}Values")

with open(file_path, "w", encoding="utf-8") as f:
    f.write(text)

print("Done translating settings.")
